"""Prepare route-aware MILP site metadata and spacing-only sensitivity outputs.

This script deliberately does NOT invent site costs, grid capacities, demand,
or an interstation-distance policy. It reads the previously generated
corridor_candidate_sites.csv and writes separate derived templates/reports.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

import pandas as pd

REQUIRED_COLUMNS = {
    "site_id",
    "route_id",
    "latitude",
    "longitude",
    "chainage_km",
    "source",
    "site_status",
}
# Exploratory values only; they are not recommendations or adopted policy.
DEFAULT_GAP_SCENARIOS_KM = (50.0, 60.0, 70.0, 80.0, 85.0, 90.0, 100.0, 120.0)


def shortest_spacing_layout(
    route_sites: pd.DataFrame, route_length_km: float, max_gap_km: float
) -> tuple[list[str] | None, list[float] | None]:
    """Find the fewest interior candidate stations bridging route endpoints.

    A path is start -> selected interior candidate sites -> end. Each segment
    must be <= max_gap_km. The route endpoints are boundaries, not selected
    stations. Candidate points exactly at either endpoint are not counted as
    interior stations in this screening report.
    """
    eps = 1e-9
    if route_length_km <= max_gap_km + eps:
        return [], []

    interior = route_sites[
        (route_sites["chainage_km"] > eps)
        & (route_sites["chainage_km"] < route_length_km - eps)
    ].sort_values(["chainage_km", "site_id"])

    # State at each candidate: minimum station count and corresponding path.
    states: list[tuple[float, str, int, list[str], list[float]]] = []
    for row in interior.itertuples(index=False):
        pos = float(row.chainage_km)
        site_id = str(row.site_id)
        best_count: int | None = None
        best_ids: list[str] | None = None
        best_positions: list[float] | None = None

        # The first selected station must be within max_gap of route start.
        if pos <= max_gap_km + eps:
            best_count = 1
            best_ids = [site_id]
            best_positions = [pos]

        # Or extend a feasible path from an earlier selected candidate.
        for prev_pos, _prev_id, prev_count, prev_ids, prev_chainages in states:
            if pos - prev_pos <= max_gap_km + eps:
                candidate_count = prev_count + 1
                if best_count is None or candidate_count < best_count:
                    best_count = candidate_count
                    best_ids = prev_ids + [site_id]
                    best_positions = prev_chainages + [pos]

        if best_count is not None and best_ids is not None and best_positions is not None:
            states.append((pos, site_id, best_count, best_ids, best_positions))

    # The final selected station must be within max_gap of route end.
    feasible = [
        state for state in states
        if route_length_km - state[0] <= max_gap_km + eps
    ]
    if not feasible:
        return None, None
    best = min(feasible, key=lambda state: (state[2], state[4]))
    return best[3], best[4]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--input",
        default="data/derived/corridor_candidate_sites.csv",
        help="Candidate site CSV generated by prepare_corridor_candidate_data.py",
    )
    parser.add_argument(
        "--output-dir",
        default="data/derived",
        help="Directory for derived output files",
    )
    parser.add_argument(
        "--gaps",
        nargs="+",
        type=float,
        default=list(DEFAULT_GAP_SCENARIOS_KM),
        help="Exploratory maximum interstation distances in km (not policy values)",
    )
    args = parser.parse_args()

    input_path = Path(args.input)
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    print("[1/5] Loading and validating candidate corridor sites...")
    if not input_path.exists():
        raise FileNotFoundError(f"Candidate-site file not found: {input_path}")
    sites = pd.read_csv(input_path)
    missing = REQUIRED_COLUMNS - set(sites.columns)
    if missing:
        raise ValueError(f"Candidate-site file is missing columns: {sorted(missing)}")
    if sites.empty:
        raise ValueError("Candidate-site file contains no candidate sites.")
    if sites["site_id"].isna().any() or sites["site_id"].duplicated().any():
        raise ValueError("site_id values must be present and unique.")
    for col in ("latitude", "longitude", "chainage_km"):
        sites[col] = pd.to_numeric(sites[col], errors="coerce")
        if sites[col].isna().any():
            raise ValueError(f"Column {col!r} contains missing/non-numeric values.")
    if (sites["chainage_km"] < 0).any():
        raise ValueError("chainage_km values must be non-negative.")

    sites["route_id"] = sites["route_id"].astype(str).str.strip()
    if (sites["route_id"] == "").any():
        raise ValueError("route_id values must be non-empty.")

    route_lengths: dict[str, float] = {}
    for route_id, group in sites.groupby("route_id", sort=True):
        ordered = group.sort_values("chainage_km")
        positions = ordered["chainage_km"].to_numpy(dtype=float)
        if len(positions) > 1 and (positions[1:] < positions[:-1]).any():
            raise ValueError(f"Chainage ordering is invalid for {route_id}.")
        if abs(float(positions[0])) > 1e-6:
            raise ValueError(
                f"{route_id} candidate sites do not include route start chainage 0."
            )
        route_lengths[str(route_id)] = float(positions[-1])
        if route_lengths[str(route_id)] <= 0:
            raise ValueError(f"{route_id} route length must be positive.")

    print(f"      {len(sites)} sites across {len(route_lengths)} corridors")
    print("[2/5] Creating a route-aware MILP site template...")
    out_sites = sites.copy()
    desired_cols = [
        "site_id", "route_id", "chainage_km", "latitude", "longitude",
        "fixed_cost", "charger_cost", "max_chargers", "grid_capacity_kw",
        "power_cost_weight", "source", "site_status",
    ]
    for col in desired_cols:
        if col not in out_sites.columns:
            out_sites[col] = pd.NA
    out_sites = out_sites[desired_cols].sort_values(
        ["route_id", "chainage_km", "site_id"]
    )
    sites_path = output_dir / "milp_corridor_sites_template.csv"
    out_sites.to_csv(sites_path, index=False)

    print("[3/5] Writing exact corridor route lengths from candidate chainage endpoints...")
    route_lengths_path = output_dir / "milp_corridor_route_lengths.json"
    route_lengths_path.write_text(
        json.dumps(
            {
                "route_lengths_km": route_lengths,
                "source": str(input_path),
                "note": (
                    "Lengths are maximum chainage values in the generated candidate-site "
                    "file. They are OSM-derived route lengths, not surveyed engineering lengths."
                ),
            },
            indent=2,
        ) + "\n",
        encoding="utf-8",
    )

    print("[4/5] Computing spacing-only sensitivity layouts...")
    sensitivity_rows: list[dict[str, Any]] = []
    layout_rows: list[dict[str, Any]] = []
    gaps = sorted(set(float(value) for value in args.gaps))
    if not gaps or any(value <= 0 for value in gaps):
        raise ValueError("All --gaps values must be positive kilometres.")

    for route_id, route_length in route_lengths.items():
        route_sites = sites[sites["route_id"] == route_id].copy()
        for max_gap in gaps:
            selected_ids, selected_chainages = shortest_spacing_layout(
                route_sites, route_length, max_gap
            )
            feasible = selected_ids is not None
            sensitivity_rows.append(
                {
                    "route_id": route_id,
                    "route_length_km": route_length,
                    "max_interstation_distance_km": max_gap,
                    "spacing_only_feasible": feasible,
                    "minimum_selected_sites_for_spacing_only": (
                        len(selected_ids) if feasible else pd.NA
                    ),
                    "selected_site_ids": ";".join(selected_ids or []),
                    "selected_chainages_km": ";".join(
                        f"{value:.6f}" for value in (selected_chainages or [])
                    ),
                    "interpretation": (
                        "Spacing-only lower bound; ignores demand, capacity, grid, land, and cost."
                    ),
                }
            )
            if feasible:
                for order, (site_id, chainage) in enumerate(
                    zip(selected_ids or [], selected_chainages or []), start=1
                ):
                    layout_rows.append(
                        {
                            "route_id": route_id,
                            "max_interstation_distance_km": max_gap,
                            "selection_order": order,
                            "site_id": site_id,
                            "chainage_km": chainage,
                        }
                    )

    sensitivity_path = output_dir / "interstation_gap_sensitivity.csv"
    pd.DataFrame(sensitivity_rows).to_csv(sensitivity_path, index=False)
    layout_path = output_dir / "interstation_gap_minimum_layouts.csv"
    pd.DataFrame(
        layout_rows,
        columns=[
            "route_id", "max_interstation_distance_km", "selection_order",
            "site_id", "chainage_km",
        ],
    ).to_csv(layout_path, index=False)

    print("[5/5] Writing readiness notes...")
    financial_missing = [
        col for col in ("fixed_cost", "charger_cost", "max_chargers", "grid_capacity_kw", "power_cost_weight")
        if col not in sites.columns or sites[col].isna().any()
    ]
    readme = [
        "MILP CORRIDOR INPUT PREPARATION",
        "================================",
        f"Input: {input_path}",
        f"Candidate sites: {len(sites)}",
        "",
        "Route lengths (km), based on max candidate chainage:",
    ]
    readme.extend(f"  {route}: {length:.6f}" for route, length in route_lengths.items())
    readme.extend(
        [
            "",
            "IMPORTANT LIMITATIONS:",
            "- Candidate sites are OSM-derived centreline screening points, not confirmed buildable parcels.",
            "- Fixed cost, charger cost, charger limits, grid capacities, and power-cost weights are not imputed.",
            "- Demand energy values and validated site-to-demand driving distances are not supplied by this script.",
            "- The sensitivity layouts enforce only maximum spacing along each route.",
            "- They are not an optimized investment plan and do not consider demand or economics.",
            "- Scenario thresholds are exploratory inputs, not engineering recommendations.",
            "- 85 km is included only as one sensitivity point; it is not equated with the separate 85 km demand-service threshold.",
            "- Route lengths come from OSM-derived geometry and should be reviewed against official alignment.",
            "",
            "Missing/incomplete site parameter columns: " + (", ".join(financial_missing) or "none"),
            "Do not feed this template to load_problem_from_csv until all required numeric fields,",
            "demand_points.csv, distances.csv, and config.json are complete and validated.",
        ]
    )
    readme_path = output_dir / "milp_corridor_input_README.txt"
    readme_path.write_text("\n".join(readme) + "\n", encoding="utf-8")

    print("\nSUMMARY")
    print(f"  Candidate sites: {len(sites)}")
    for route, length in route_lengths.items():
        count = int((sites["route_id"] == route).sum())
        print(f"  {route}: {count} sites | length={length:.6f} km")
    print(f"  Exploratory gap thresholds: {', '.join(f'{x:g}' for x in gaps)} km")
    print("  Site cost/grid fields: retained as supplied; no values invented")
    print("\nSaved:")
    for path in (sites_path, route_lengths_path, sensitivity_path, layout_path, readme_path):
        print(f"  {path}")
    print("\nNOTE: spacing-only layouts are feasibility lower bounds, not MILP solutions.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
